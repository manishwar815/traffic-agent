"""E-challan PDF (one page, A4) made with ReportLab.

The layout follows the usual Indian e-challan: challan number, date/time,
place, vehicle number, offence with its Motor Vehicles Act section, fine,
and the camera evidence. It is clearly marked as generated by this
academic system, not by any police department.
"""
from __future__ import annotations

import time
from pathlib import Path
from typing import Optional

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.lib.utils import ImageReader
from reportlab.pdfgen import canvas

VIOLATION_TITLES = {
    "red_light": "Jumping red light",
    "wrong_way": "Driving on the wrong side / against traffic",
    "no_helmet": "Riding a two-wheeler without helmet",
    "speeding": "Over-speeding",
}


def make_challan_pdf(path: str | Path, info: dict, snapshot: Optional[str | Path] = None,
                     closeup: Optional[str | Path] = None) -> Path:
    """info keys: challan_no, ts, junction, lat, lon, approach, plate, plate_status, vehicle,
    violation, section, amount, details (dict of extra measured values)."""
    path = Path(path)
    W, H = A4
    c = canvas.Canvas(str(path), pagesize=A4)
    c.setTitle(f"e-Challan {info['challan_no']}")
    c.setAuthor("Traffic Agent")
    m = 18 * mm

    # header band
    c.setFillColor(colors.HexColor("#14213d"))
    c.rect(0, H - 34 * mm, W, 34 * mm, fill=1, stroke=0)
    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 20)
    c.drawString(m, H - 17 * mm, "e-CHALLAN")
    c.setFont("Helvetica", 10)
    c.drawString(m, H - 24 * mm, "Traffic violation notice, generated automatically by Traffic Agent")
    c.setFont("Helvetica-Bold", 11)
    c.drawRightString(W - m, H - 17 * mm, f"No. {info['challan_no']}")
    c.setFont("Helvetica", 10)
    c.drawRightString(W - m, H - 24 * mm, time.strftime("%d %b %Y, %H:%M:%S", time.localtime(info["ts"])))

    # details table
    y = H - 46 * mm
    title = VIOLATION_TITLES.get(info["violation"], info["violation"])
    plate = info.get("plate") or "NOT READ (manual review)"
    rows = [
        ("Vehicle number", plate),
        ("Vehicle type", info.get("vehicle", "-")),
        ("Offence", title),
        ("Law", info.get("section") or "-"),
        ("Place", f"{info.get('junction', '-')}, {info.get('approach', '-')} approach"),
        ("GPS", f"{info.get('lat', 0):.5f}, {info.get('lon', 0):.5f}"),
    ]
    for k, v in (info.get("details") or {}).items():
        rows.append((k, str(v)))
    rows.append(("Status", info.get("plate_status", "ISSUED")))
    c.setFillColor(colors.black)
    for k, v in rows:
        c.setFont("Helvetica", 10)
        c.setFillColor(colors.HexColor("#555555"))
        c.drawString(m, y, k)
        c.setFont("Helvetica-Bold", 11)
        c.setFillColor(colors.black)
        c.drawString(m + 42 * mm, y, str(v)[:80])
        y -= 7 * mm
    c.setStrokeColor(colors.HexColor("#cccccc"))
    c.line(m, y + 3 * mm, W - m, y + 3 * mm)

    # fine box
    y -= 6 * mm
    c.setFillColor(colors.HexColor("#fdecea"))
    c.roundRect(m, y - 8 * mm, W - 2 * m, 16 * mm, 3 * mm, fill=1, stroke=0)
    c.setFillColor(colors.HexColor("#b3261e"))
    c.setFont("Helvetica-Bold", 16)
    c.drawString(m + 5 * mm, y - 2 * mm, f"Fine amount: Rs. {info['amount']:,}")
    c.setFont("Helvetica", 9)
    c.setFillColor(colors.HexColor("#333333"))
    c.drawRightString(W - m - 5 * mm, y - 2 * mm, "Pay within 60 days or contest at the traffic court")
    y -= 16 * mm

    # evidence images
    c.setFont("Helvetica-Bold", 11)
    c.setFillColor(colors.black)
    c.drawString(m, y, "Camera evidence")
    y -= 4 * mm
    box_w = W - 2 * m
    if snapshot and Path(snapshot).exists():
        img = ImageReader(str(snapshot))
        iw, ih = img.getSize()
        w = box_w if not closeup else box_w * 0.68
        h = w * ih / iw
        h = min(h, y - 30 * mm)
        w = h * iw / ih
        c.drawImage(img, m, y - h, w, h)
        if closeup and Path(closeup).exists():
            ci = ImageReader(str(closeup))
            cw, ch = ci.getSize()
            w2 = box_w - w - 4 * mm
            h2 = min(h, w2 * ch / cw)
            w2 = h2 * cw / ch
            c.drawImage(ci, m + w + 4 * mm, y - h2, w2, h2)
        y -= h + 8 * mm

    # footer
    c.setFont("Helvetica-Oblique", 8)
    c.setFillColor(colors.HexColor("#777777"))
    c.drawString(m, 14 * mm, "Generated by Traffic Agent (academic project). Not issued by any police department; "
                             "for demonstration of automated enforcement only.")
    c.showPage()
    c.save()
    return path
